/** Clinical assessment sections for Skilled Nurse Visit documentation. */

export type AssessmentOption = {
  id: string;
  label: string;
  /** Optional subgroup label (e.g. Mobility, Assistive Device) */
  group?: string;
  /** When selected, show these nested choices */
  children?: string[];
  /** Dropdown options shown when checked (web Labs-style type/method select) */
  selectOptions?: string[];
  selectPlaceholder?: string;
};

export type AssessmentExtraField = {
  id: string;
  label: string;
  placeholder?: string;
  voice?: boolean;
};

export type AssessmentSection = {
  id: string;
  title: string;
  color: string;
  options: AssessmentOption[];
  showComments?: boolean;
  commentPlaceholder?: string;
  commentLabel?: string;
  /** Show Voice Input next to Comments (matches web nurse note) */
  commentVoice?: boolean;
  /** Extra textareas below options (e.g. Caregiver Availability) */
  extraFields?: AssessmentExtraField[];
  /** Form data key for the comment textarea (web field name) */
  commentFormKey?: string;
};

